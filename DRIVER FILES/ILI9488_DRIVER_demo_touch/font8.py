def character_code(character):
    """
    Convert a character or integer into a supported character code.

    Unsupported characters are replaced with '?'.
    """
    if isinstance(character, int):
        code = character
    else:
        text = str(character)

        if not text:
            code = REPLACEMENT_CHARACTER
        else:
            code = ord(text[0])

    if code < FIRST_CHARACTER or code > LAST_CHARACTER:
        return REPLACEMENT_CHARACTER

    return code


def glyph_offset(character):
    """
    Return the first FONT_DATA index for a character.
    """
    code = character_code(character)

    return (
        code - FIRST_CHARACTER
    ) * BYTES_PER_CHARACTER


def glyph_row(character, row):
    """
    Return one eight-pixel bitmap row for a character.

    Parameters
    ----------
    character
        Character string or integer character code.
    row : int
        Row from 0 through 7.
    """
    row = int(row)

    if row < 0 or row >= FONT_HEIGHT:
        return 0

    return FONT_DATA[glyph_offset(character) + row]
